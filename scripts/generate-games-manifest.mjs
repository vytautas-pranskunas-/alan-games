#!/usr/bin/env node
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gamesDir = join(root, 'apps/web/src/games');
const publicGamesDir = join(root, 'apps/web/public/assets/games');
const manifestPath = join(root, 'apps/web/src/app/games/games.manifest.ts');

mkdirSync(gamesDir, { recursive: true });
if (existsSync(publicGamesDir)) {
  rmSync(publicGamesDir, { recursive: true, force: true });
}
mkdirSync(publicGamesDir, { recursive: true });

const slugs = readdirSync(gamesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const games = [];

for (const slug of slugs) {
  const metaPath = join(gamesDir, slug, 'game.json');
  if (!existsSync(metaPath)) {
    console.warn(`Skipping ${slug}: missing game.json`);
    continue;
  }
  const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
  const entry = {
    title: meta.title ?? slug,
    slug: meta.slug ?? slug,
    genre: meta.genre ?? 'arcade',
    dateAdded: meta.dateAdded ?? new Date().toISOString().slice(0, 10),
    shortDescription: meta.shortDescription ?? '',
    cover: meta.cover ?? 'cover.png',
    entry: meta.entry ?? 'index.html',
  };
  games.push(entry);
  cpSync(join(gamesDir, slug), join(publicGamesDir, slug), { recursive: true });
}

games.sort((a, b) => (a.dateAdded < b.dateAdded ? 1 : a.dateAdded > b.dateAdded ? -1 : 0));

const file = `import { GameMeta } from './game.model';

/** Generated by \`npm run games:sync\` — do not edit by hand. */
export const GAMES_MANIFEST: GameMeta[] = ${JSON.stringify(games, null, 2)};
`;

writeFileSync(manifestPath, file);
console.log(`Synced ${games.length} game(s) → public/assets/games + games.manifest.ts`);
